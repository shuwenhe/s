// =============================================================================
// 1. BASIC CONCEPTS / 基本概念
// =============================================================================

/*
┌─────────────────────────────────────────────────────────────────────────┐
│ OWNERSHIP / 所有权                                                      │
├─────────────────────────────────────────────────────────────────────────┤
│                                                                         │
│ 定义: 谁拥有一个资源？                                                   │
│ 特点:                                                                    │
│   • 每个值有一个所有者                                                   │
│   • 同时只能有一个所有者                                                 │
│   • 所有者离开作用域时，值被销毁                                         │
│                                                                         │
│ 示例:                                                                    │
│   r := newResource(10)   // r是所有者                                    │
│                                                                         │
└─────────────────────────────────────────────────────────────────────────┘
*/

/*
┌─────────────────────────────────────────────────────────────────────────┐
│ MOVE / 转移                                                             │
├─────────────────────────────────────────────────────────────────────────┤
│                                                                         │
│ 定义: 所有权的转移                                                       │
│ 语法: r2 := r1                                                          │
│ 结果:                                                                    │
│   • r1不再有效                                                          │
│   • r2获得所有权                                                        │
│                                                                         │
│ 示例:                                                                    │
│   r1 := newResource(10)                                                 │
│   r2 := r1               // r1的所有权转移给r2                           │
│   // r1不能再使用        // r2现在是所有者                               │
│                                                                         │
└─────────────────────────────────────────────────────────────────────────┘
*/

/*
┌─────────────────────────────────────────────────────────────────────────┐
│ BORROW / 借用                                                           │
├─────────────────────────────────────────────────────────────────────────┤
│                                                                         │
│ 定义: 不转移所有权的访问                                                 │
│ 分类:                                                                    │
│   1. Shared Borrow (共享借用)   - &resource  (只读)                      │
│   2. Mutable Borrow (可变借用)  - &mut resource  (读写)                  │
│                                                                         │
│ 规则:                                                                    │
│   • 多个共享借用可共存                                                    │
│   • 可变借用必须独占                                                      │
│   • 共享和可变借用不能混合                                                │
│                                                                         │
│ 示例:                                                                    │
│   // 共享借用                                                            │
│   ref := &resource                                                      │
│   val := borrowShared(ref)                                              │
│                                                                         │
│   // 可变借用                                                            │
│   mut_ref := &mut resource                                              │
│   borrowMutable(mut_ref)                                                │
│                                                                         │
└─────────────────────────────────────────────────────────────────────────┘
*/

/*
┌─────────────────────────────────────────────────────────────────────────┐
│ DROP / 析构                                                             │
├─────────────────────────────────────────────────────────────────────────┤
│                                                                         │
│ 定义: 资源的自动清理                                                     │
│ 时机: 当所有者离开作用域时                                               │
│ 机制: 自动调用析构函数                                                    │
│                                                                         │
│ 示例:                                                                    │
│   {                                                                      │
│       r := newResource(10)   // r获取所有权                             │
│       // 使用r                                                           │
│   }   // r离开作用域，自动销毁，内存释放                                  │
│                                                                         │
└─────────────────────────────────────────────────────────────────────────┘
*/

/*
┌─────────────────────────────────────────────────────────────────────────┐
│ LIFETIME / 生命周期                                                     │
├─────────────────────────────────────────────────────────────────────────┤
│                                                                         │
│ 定义: 引用的有效期                                                       │
│ 规则: 引用不能比其所有者活得更长                                          │
│                                                                         │
│ 示例:                                                                    │
│   // VALID                                                               │
│   func valid() int {                                                    │
│       value := box(42)                                                  │
│       ptr := &value                                                     │
│       return *ptr        // OK - value仍然有效                          │
│   }                                                                      │
│                                                                         │
│   // INVALID                                                             │
│   func invalid() *int {                                                 │
│       value := box(42)                                                  │
│       return &value      // ERROR - value离开作用域                     │
│   }                                                                      │
│                                                                         │
└─────────────────────────────────────────────────────────────────────────┘
*/

// =============================================================================
// 2. COMMON PATTERNS / 常见模式
// =============================================================================

/*
┌─────────────────────────────────────────────────────────────────────────┐
│ PATTERN 1: Ownership Transfer                                          │
│ 模式1: 所有权转移                                                       │
├─────────────────────────────────────────────────────────────────────────┤
│                                                                         │
│ 何时使用: 函数需要完全控制资源                                            │
│ 签名: func process(r Resource) int                                      │
│                                                                         │
│ 示例:                                                                    │
│   func consumeResource(r Resource) int {                                │
│       return *r.ptr     // r在函数中有效                                │
│   }   // r在这里销毁                                                     │
│                                                                         │
│   caller() {                                                            │
│       r := newResource(10)                                              │
│       result := consumeResource(r)  // r的所有权转移                   │
│       // r不能再使用                                                    │
│   }                                                                      │
│                                                                         │
└─────────────────────────────────────────────────────────────────────────┘
*/

/*
┌─────────────────────────────────────────────────────────────────────────┐
│ PATTERN 2: Borrowing (Shared)                                          │
│ 模式2: 借用（共享）                                                     │
├─────────────────────────────────────────────────────────────────────────┤
│                                                                         │
│ 何时使用: 函数只需读取资源                                               │
│ 签名: func read(r *Resource) int                                        │
│                                                                         │
│ 示例:                                                                    │
│   func readData(r *Resource) int {                                      │
│       return *r.ptr     // r仍然有效                                    │
│   }                                                                      │
│                                                                         │
│   caller() {                                                            │
│       r := newResource(10)                                              │
│       val1 := readData(&r)  // 共享借用                                │
│       val2 := readData(&r)  // 多个可以共存                            │
│       val3 := readData(&r)  // r仍然是所有者                           │
│   }                                                                      │
│                                                                         │
└─────────────────────────────────────────────────────────────────────────┘
*/

/*
┌─────────────────────────────────────────────────────────────────────────┐
│ PATTERN 3: Borrowing (Mutable)                                         │
│ 模式3: 借用（可变）                                                     │
├─────────────────────────────────────────────────────────────────────────┤
│                                                                         │
│ 何时使用: 函数需要修改资源                                               │
│ 签名: func modify(r *Resource) ()                                       │
│                                                                         │
│ 示例:                                                                    │
│   func modifyData(r *Resource) () {                                     │
│       *r.ptr = *r.ptr + 100  // 可以修改                               │
│   }                                                                      │
│                                                                         │
│   caller() {                                                            │
│       r := newResource(10)                                              │
│       modifyData(&r)    // 可变借用                                     │
│       // 一次只能有一个可变借用                                          │
│   }                                                                      │
│                                                                         │
└─────────────────────────────────────────────────────────────────────────┘
*/

/*
┌─────────────────────────────────────────────────────────────────────────┐
│ PATTERN 4: Return Ownership                                            │
│ 模式4: 返回所有权                                                       │
├─────────────────────────────────────────────────────────────────────────┤
│                                                                         │
│ 何时使用: 函数创建或构造资源                                              │
│ 签名: func create() Resource                                            │
│                                                                         │
│ 示例:                                                                    │
│   func allocate() Resource {                                            │
│       r := newResource(42)                                              │
│       return r  // 所有权返回给调用者                                   │
│   }                                                                      │
│                                                                         │
│   caller() {                                                            │
│       r := allocate()   // 获得所有权                                   │
│       // r现在属于caller                                                │
│   }                                                                      │
│                                                                         │
└─────────────────────────────────────────────────────────────────────────┘
*/

