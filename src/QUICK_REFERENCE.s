// 8. SIDE-BY-SIDE COMPARISON / 代码对比
// =============================================================================

/*
C语言（手动管理）                S语言（自动所有权）
─────────────────────────────     ─────────────────────────────

Resource* create() {              func create() Resource {
    Resource* r =                     r := Resource{
        malloc(sizeof(...));              ptr: box(...),
    return r;                       }
}                                 return r
                                  }

void destroy(Resource* r) {       // 自动调用
    free(r->ptr);                 // 销毁时自动释放
    free(r);
}

Resource* caller() {              func caller() Resource {
    Resource* r = create();           r := create()
    // 使用r                          // 使用r
    destroy(r);                   }   // r在这里自动销毁
    return ...;
}

对比:
✗ C 需要手动free()               ✓ S 自动释放
✗ C 容易忘记free()               ✓ S 不可能内存泄漏
✗ C 容易double-free               ✓ S 编译时检查
✓ C 性能完全可控                 ✓ S 性能相当
                                  ✓ S 无GC暂停
*/

