// 7. PERFORMANCE TIPS / 性能提示
// =============================================================================

/*
┌────────────────────────────────────────────────────────────────────────┐
│ 性能优化建议                                                            │
├────────────────────────────────────────────────────────────────────────┤
│                                                                        │
│ 1. 优先使用借用而非所有权转移                                            │
│    func process(r *Resource)  // 快速                                  │
│    vs                                                                  │
│    func process(r Resource)   // 需要初始化                            │
│                                                                        │
│ 2. 小对象在栈上分配                                                     │
│    type Small struct { x int }  // 栈分配更快                          │
│                                                                        │
│ 3. 在块中限制借用生命周期                                                │
│    {                                                                   │
│        ref := &x                                                       │
│        // 使用ref                                                      │
│    }  // ref生命周期在这里结束，x可以被修改                            │
│                                                                        │
│ 4. 返回所有权而不是通过指针输出                                          │
│    return Result { value: x }  // 清晰，编译器可优化                   │
│                                                                        │
│ 5. 避免不必要的复制                                                     │
│    使用box(value) 而不是复制大结构                                      │
│                                                                        │
└────────────────────────────────────────────────────────────────────────┘
*/

