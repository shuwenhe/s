// =============================================================================
// 5. DECISION TREE / 决策树
// =============================================================================

/*
我想创建一个资源
    │
    ├─ 在函数中分配？
    │   └─ 是 → return Resource
    │
    └─ 由调用者分配？
        └─ 是 → func(r Resource) 或 func(r *Resource)


我想在函数中使用一个资源
    │
    ├─ 需要修改它？
    │   ├─ 是 → func(r *Resource)   // 可变借用
    │   └─ 否 → func(r *Resource)   // 共享借用
    │
    ├─ 需要完全控制它？
    │   └─ 是 → func(r Resource)    // 转移所有权
    │
    └─ 只是读取它？
        └─ 是 → func(r *Resource)   // 共享借用


我想在多个地方使用一个资源
    │
    ├─ 多个位置只读？
    │   └─ 是 → 多个共享借用 OK
    │
    ├─ 多个位置修改？
    │   └─ 否 → 编译错误，需要序列化
    │
    └─ 一个位置修改，其他读取？
        └─ 否 → 编译错误，借用冲突
*/

// =============================================================================
// 6. ERROR CHECKLIST / 错误检查表
// =============================================================================

/*
┌────────────────────────────────────────────────────────────────────────┐
│ 编译错误排查                                                            │
├────────────────────────────────────────────────────────────────────────┤
│                                                                        │
│ ❌ "use of moved value 'x'"                                           │
│    → x被转移到其他变量，无法再用                                        │
│    → 检查: r2 := r1 之后是否还用r1                                     │
│    → 修复: 使用借用替代 (&r1) 或保持所有权                             │
│                                                                        │
│ ❌ "cannot borrow 'x' as mutable more than once"                      │
│    → 同时有两个可变借用                                                  │
│    → 检查: &mut x 出现多次                                             │
│    → 修复: 用块限制借用生命周期                                         │
│                                                                        │
│ ❌ "cannot borrow 'x' as mutable when already borrowed as immutable"  │
│    → 混合了共享和可变借用                                                │
│    → 检查: &x 和 &mut x 同时存在                                       │
│    → 修复: 移除共享借用或延迟可变借用                                   │
│                                                                        │
│ ❌ "reference does not live long enough"                              │
│    → 返回的引用超过了其所有者的生命周期                                  │
│    → 检查: 返回 &x，但x在函数内创建                                     │
│    → 修复: 返回所有权(return x) 而不是借用                             │
│                                                                        │
└────────────────────────────────────────────────────────────────────────┘
*/

